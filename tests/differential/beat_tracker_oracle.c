/* Five exact 0.5 s gaps take learned_intervals from 0 through 5, so the blend
 * weight changes from 0.42 to 0.20 in the middle of one case and the 0.7 s
 * outlier at the end is absorbed by whichever weight is then current. Two
 * separate primings would let a wrong threshold pass by being wrong twice. */
static const Input WEIGHT_TRANSITION[] = {
    { 0.0, 1, 0.5f },
    { 0.5, 1, 0.5f },
    { 1.0, 1, 0.5f },
    { 1.5, 1, 0.5f },
    { 2.0, 1, 0.5f },
    { 2.5, 1, 0.5f },
    { 3.0, 1, 0.5f },
    { 3.7, 1, 0.5f },
    { 4.2, 1, 0.5f },
    { 4.7, 1, 0.5f },
};

/*
 * Every input the tracker refuses, from a fresh tracker and then from a running
 * one, followed by a valid call proving the refusals left no residue.
 *
 * The huge finite time is not padding: 1e18/0.5 is a whole double, so the
 * fractional part is exactly zero and the phase reads 0 -- and the next small
 * time is then a backwards jump, which restarts. A tracker that survived a
 * seek to the end of a 30-year track is worth one row.
 */
static void run_rejections(void)
{
    static const Input FRESH[] = {
        { -1.0,      0, 0.0f },
        { -0.0,      0, 0.0f },   /* not negative: accepted */
    };
    run_case("reject_fresh", FRESH, sizeof FRESH/sizeof FRESH[0]);

    Beat_Tracker tracker;
    beat_tracker_reset(&tracker);
    int index = 0;
    step(&tracker, "reject_running", index++, 0.0, true, 0.5);
    step(&tracker, "reject_running", index++, 0.5, true, 0.5);
    step(&tracker, "reject_running", index++, NAN, false, 0.0f);
    step(&tracker, "reject_running", index++, INFINITY, false, 0.0f);
    step(&tracker, "reject_running", index++, -INFINITY, false, 0.0f);
    step(&tracker, "reject_running", index++, -1.0e-300, false, 0.0f);
    step(&tracker, "reject_running", index++, 1.0, false, (float)NAN);
    step(&tracker, "reject_running", index++, 1.0, false, (float)INFINITY);
    step(&tracker, "reject_running", index++, 1.0, false, -(float)INFINITY);
    step(&tracker, "reject_running", index++, 1.0, false, -0.1f);
    /* Normal rather than subnormal on purpose: a decimal literal in the
     * subnormal range is a needless bet that both compilers round it the same
     * way, and the thing under test is the sign check. */
    step(&tracker, "reject_running", index++, 1.0, false, -1.0e-30f);
    /* Nothing above touched the state, so this reads as if it came straight
     * after the 0.5 s onset. */
    step(&tracker, "reject_running", index++, 1.0, false, 0.5f);
    step(&tracker, "reject_running", index++, 1.0e18, false, 0.5f);
    step(&tracker, "reject_running", index++, 2.0, false, 0.5f);
    /* Unsuffixed on purpose. Writing this as `3.4028235e38f` made it a *float*
     * literal widened to the double parameter, which is a different number from
     * the same decimal parsed as a double -- and the two harnesses disagreed by
     * 3.4e30 on the very first run. The input columns are echoed so that a drift
     * between the two duplicated generators fails here, in a key column, instead
     * of being blamed on the port. */
    step(&tracker, "reject_running", index++, 1.0e300, false, 0.5f);
}

/*
 * `reset` is the public "forget everything", and it is deliberately *not* the
 * internal restart a discontinuity performs: the restart keeps a credible
 * interval across the gap, reset drops it. Both are dumped here from the same
 * learned state so the difference is a pair of rows rather than a claim.
 */
static void run_reset_versus_seek(void)
{
    Beat_Tracker tracker;
    beat_tracker_reset(&tracker);
    int index = 0;
    for (int beat = 0; beat < 6; ++beat) {
        step(&tracker, "reset_vs_seek", index++, (double)beat*0.6, true, 0.5f);
    }
    /* A forward jump past 0.75 s: new phase reference, tempo survives. */
    step(&tracker, "reset_vs_seek", index++, 30.0, false, 0.0f);
    step(&tracker, "reset_vs_seek", index++, 30.25, false, 0.0f);
    /* Now the explicit reset from the same shape of state. */
    dump_reset(&tracker, "reset_vs_seek", index++);
    step(&tracker, "reset_vs_seek", index++, 30.5, false, 0.0f);
    step(&tracker, "reset_vs_seek", index++, 30.75, false, 0.0f);
}

/*
 * A `false` return with no invalid input.
 *
 * position is 0.99999999999 as a double, which is inside [0, 1); narrowed to a
 * float it becomes exactly 1.0, and the final check refuses it. So the tracker
 * declines a phase it computed itself -- and writes it anyway, which is the
 * difference this case exists to pin.
 *
 * Written as a deliberate case, but it turns out not to be a corner: the grid
 * above reaches the same state 187 times without trying, because accumulated tick
 * drift puts the position a hair under an exact multiple of the interval whenever
 * the tick nearly divides it. `restart_boundary` index 5 hits it too, from the
 * 0.75 s gaps. Neither test suite has a case for it.
 */
static const Input FLOAT_ROUNDS_TO_ONE[] = {
    { 0.0,            0, 0.0f },
    { 0.499999999995, 0, 0.0f },
    { 0.5,            0, 0.0f },
};

int main(void)
{
    run_grid();

    run_case("restart_boundary", RESTART_BOUNDARY,
             sizeof RESTART_BOUNDARY/sizeof RESTART_BOUNDARY[0]);
    run_case("gap_min_boundary", GAP_MIN_BOUNDARY,
             sizeof GAP_MIN_BOUNDARY/sizeof GAP_MIN_BOUNDARY[0]);
    run_case("gap_max_boundary", GAP_MAX_BOUNDARY,
             sizeof GAP_MAX_BOUNDARY/sizeof GAP_MAX_BOUNDARY[0]);
    run_strength_floor();
    run_case("tempo_fold", TEMPO_FOLD,
             sizeof TEMPO_FOLD/sizeof TEMPO_FOLD[0]);
    run_case("weight_transition", WEIGHT_TRANSITION,
             sizeof WEIGHT_TRANSITION/sizeof WEIGHT_TRANSITION[0]);
    run_case("float_rounds_to_one", FLOAT_ROUNDS_TO_ONE,
             sizeof FLOAT_ROUNDS_TO_ONE/sizeof FLOAT_ROUNDS_TO_ONE[0]);
    run_rejections();
    run_reset_versus_seek();

    /*
     * Mechanism divergences, stated rather than quietly excluded. Both are inputs
     * each side cannot express: C takes bare pointers and documents a null tracker
     * or a null out-parameter as a refusal, and Rust takes `&mut self` and returns
     * an enum, so neither is an input it can be handed.
     *
     * There used to be a third entry here claiming the out-of-range write was an
     * oracle quirk the port deliberately did not reproduce. That was wrong -- the
     * C's caller uses the written value -- and writing the claim down is what
     * exposed it. It is now a compared column on every `step` row instead.
     */
    printf("divergence null_tracker c_returns_false\n");
    printf("divergence null_phase_out c_returns_false\n");

    /* Proof the two refusals above are what the oracle actually does, rather
     * than what its header says. Reading the .c is the rule; running it is
     * better. */
    {
        Beat_Tracker tracker;
        beat_tracker_reset(&tracker);
        float phase = 7.0f;
        bool null_tracker = beat_tracker_update(NULL, 0.0, false, 0.0f, &phase);
        bool null_phase = beat_tracker_update(&tracker, 0.0, false, 0.0f, NULL);
        printf("oracle_only null_tracker_returned %d\n", null_tracker ? 1 : 0);
        printf("oracle_only null_phase_returned %d\n", null_phase ? 1 : 0);
        printf("oracle_only phase_untouched_by_null_tracker %s\n", num((double)phase));
    }

    return 0;
}
