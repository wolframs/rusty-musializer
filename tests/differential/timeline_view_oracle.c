/*
 * Differential harness: dumps the *oracle's* timeline view over a wide grid of
 * view states, strip geometries and operation sequences, so the Rust port can be
 * compared against it numerically instead of by property assertion.
 *
 * This compiles `../musializer/src/timeline_view.c` from the frozen C repository
 * unmodified. It reads that tree and writes only into our own `build/`; the
 * oracle is never modified, and its own build directory is never touched.
 *
 * Why this module gets a harness rather than a review: timeline_view is the
 * single seconds<->pixel conversion the whole strip goes through -- the tick
 * ladder, the playhead, the scrubber, the event markers, the lyric blocks and the
 * waveform envelope's per-column bin range all call into it. That is deliberate
 * (`timeline_view.h:6-11`) and it is also why a drift here is invisible: if the
 * view is wrong, every element on the strip is wrong *consistently*, so the strip
 * still photographs as a self-coherent picture.
 *
 * The port's own tests were almost entirely property assertions -- `is_finite()`,
 * `span <= duration + 1e-9`, `span/step >= 2.0` -- which a genuinely wrong
 * formula would survive. `../musializer/tests/test_timeline_view.c` pins 32 exact
 * values, and hand-transcribing those would risk a typo or, worse, a number
 * copied from our own output. A differential comparison cannot be tautological.
 *
 * Everything printed here is generated by plain double arithmetic with explicit
 * evaluation order, duplicated in `timeline_view_dump.rs` on purpose. Two copies
 * of a grid generator is normally a smell; here it is the entire mechanism,
 * because a shared generator could hide the very difference the test looks for.
 * The grid *inputs* are printed alongside the outputs so the two tables are
 * themselves compared: if the duplicated grids ever drift apart, the key columns
 * fail before the value columns do.
 *
 * Build and run through tools/differential_timeline_view.sh.
 */

#include <math.h>
#include <stddef.h>
#include <stdio.h>

#include "timeline_view.h"

/*
 * Seventeen digits after the point, in exponential form. A double round-trips in
 * seventeen significant digits, so printing is not the limiting factor and any
 * delta the comparison reports is arithmetic rather than formatting. Exponential
 * form also keeps a float token from ever looking like an integer to the
 * comparison script, which is how it knows which columns to compare exactly.
 *
 * Non-finite values get a *label* instead of `nan`/`inf`. That is not cosmetic:
 * `nan` and `inf` both parse as floats in Python, and `abs(nan - nan) > tol` is
 * False, so a column of them would pass unconditionally -- a silent hole the
 * project has already been bitten by once. These labels contain no digits and no
 * spelling `float()` accepts, so they fall through to the exact-string branch and
 * a NaN where a number belongs fails loudly. C spells them the same way the Rust
 * side does because both sides spell them by hand.
 */
#define FLOAT_FMT "%.17e"

/*
 * A rotating pool so several numbers can appear in one printf. Argument
 * evaluation order is unspecified in C, which is exactly why each call must get
 * its own buffer rather than share one; no record below prints more than eight
 * numbers.
 */
#define NUM_BUF_COUNT 12
static char num_bufs[NUM_BUF_COUNT][48];
static int num_buf_next = 0;

static const char *num(double value)
{
    if (isnan(value)) return "not_a_number";
    if (isinf(value)) return value > 0.0 ? "positive_infinity" : "negative_infinity";
    char *buf = num_bufs[num_buf_next];
    num_buf_next = (num_buf_next + 1)%NUM_BUF_COUNT;
    snprintf(buf, sizeof num_bufs[0], FLOAT_FMT, value);
    return buf;
}

