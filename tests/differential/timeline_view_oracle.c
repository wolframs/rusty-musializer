static void dump_constants(void)
{
    printf("constant min_span %s\n", num(TIMELINE_VIEW_MIN_SPAN_SECONDS));
    printf("constant reveal_margin %s\n", num(TIMELINE_VIEW_REVEAL_MARGIN));
}

static void dump_reset_and_clamp(void)
{
    size_t duration_count = sizeof durations_a/sizeof durations_a[0];
    size_t state_count = sizeof states_a/sizeof states_a[0];

    for (size_t d = 0; d < duration_count; ++d) {
        Timeline_View view = {0.0, 0.0};
        timeline_view_reset(&view, durations_a[d]);
        printf("reset %s %s %s %d\n", num(durations_a[d]),
               num(view.start_seconds), num(view.span_seconds),
               timeline_view_is_whole(&view, durations_a[d]) ? 1 : 0);
    }

    for (size_t d = 0; d < duration_count; ++d) {
        for (size_t s = 0; s < state_count; ++s) {
            Timeline_View view;
            view.start_seconds = states_a[s].start;
            view.span_seconds = states_a[s].span;
            /* is_whole *before* the clamp, because the non-finite-span branch
             * answers true and is unreachable once clamp has run. */
            int raw_whole = timeline_view_is_whole(&view, durations_a[d]) ? 1 : 0;
            timeline_view_clamp(&view, durations_a[d]);
            printf("clamp %s %s %s %d %s %s %d\n",
                   num(durations_a[d]), num(states_a[s].start),
                   num(states_a[s].span), raw_whole,
                   num(view.start_seconds), num(view.span_seconds),
                   timeline_view_is_whole(&view, durations_a[d]) ? 1 : 0);
        }
    }
}

static void dump_conversions(void)
{
    size_t duration_count = sizeof durations_b/sizeof durations_b[0];
    size_t geom_count = sizeof geoms_b/sizeof geoms_b[0];
    size_t seconds_count = sizeof seconds_b/sizeof seconds_b[0];
    size_t x_count = sizeof xs_b/sizeof xs_b[0];

    for (size_t d = 0; d < duration_count; ++d) {
        double duration = durations_b[d];
        for (int kind = 0; kind < 9; ++kind) {
            Timeline_View view = probe_view(kind, duration);
            /* The state itself, so a conversion difference can be told apart
             * from a difference in how the state was reached. */
            printf("probe %s %d %s %s\n", num(duration), kind,
                   num(view.start_seconds), num(view.span_seconds));
            for (size_t g = 0; g < geom_count; ++g) {
                double left = geoms_b[g].left;
                double width = geoms_b[g].width;
                printf("spp %s %d %s %s\n", num(duration), kind, num(width),
                       num(timeline_view_seconds_per_pixel(&view, width)));
                for (size_t i = 0; i < seconds_count; ++i) {
                    printf("x_at %s %d %s %s %s %s\n", num(duration), kind,
                           num(left), num(width), num(seconds_b[i]),
                           num(timeline_view_x_at(&view, seconds_b[i], left,
                                                  width)));
                }
                for (size_t i = 0; i < x_count; ++i) {
                    printf("seconds_at %s %d %s %s %s %s\n", num(duration), kind,
                           num(left), num(width), num(xs_b[i]),
                           num(timeline_view_seconds_at(&view, xs_b[i], left,
                                                        width, duration)));
                }
                /* The round trip the C's own test checks at 1e-6
                 * (`tests/test_timeline_view.c:151-160`), here at every eleventh
                 * of the strip for every geometry rather than one zoom level. */
                for (int f = 0; f <= 10; ++f) {
                    double fraction = (double)f/10.0;
                    double x = left + width*fraction;
                    double seconds = timeline_view_seconds_at(&view, x, left,
                                                              width, duration);
                    double back = timeline_view_x_at(&view, seconds, left, width);
                    printf("round_trip %s %d %s %s %s %s %s\n", num(duration),
                           kind, num(left), num(width), num(fraction),
                           num(seconds), num(back));
                }
            }
        }
    }
}

static void dump_zoom(void)
{
    size_t duration_count = sizeof durations_c/sizeof durations_c[0];
    size_t factor_count = sizeof factors_c/sizeof factors_c[0];
    size_t anchor_count = sizeof anchors_c/sizeof anchors_c[0];

    for (size_t d = 0; d < duration_count; ++d) {
        double duration = durations_c[d];
        for (int kind = 0; kind < 4; ++kind) {
            for (size_t f = 0; f < factor_count; ++f) {
                for (size_t a = 0; a < anchor_count; ++a) {
                    Timeline_View view = base_view(kind, duration);
                    /* Where the anchor sat before the zoom, and where it sits
                     * after. Wheel zoom feeling attached to the pointer is
                     * exactly these two numbers agreeing, and it is the property
                     * an off-by-a-fraction formulation still looks plausible
                     * without. */
                    double before = timeline_view_x_at(&view, anchors_c[a],
                                                       STRIP_LEFT, STRIP_WIDTH);
                    timeline_view_zoom(&view, duration, factors_c[f],
                                       anchors_c[a]);
                    double after = timeline_view_x_at(&view, anchors_c[a],
                                                      STRIP_LEFT, STRIP_WIDTH);
                    printf("zoom %s %d %s %s %s %s %s %d %s\n", num(duration),
                           kind, num(factors_c[f]), num(anchors_c[a]),
                           num(before), num(view.start_seconds),
                           num(view.span_seconds),
                           timeline_view_is_whole(&view, duration) ? 1 : 0,
                           num(after));
                }
            }
        }
    }
}

/*
 * reveal and pan get their own sweep rather than only appearing inside the
 * chains, because between them they are the whole of follow-playback and of
 * dragging the strip, and a margin applied to the wrong edge still keeps the
 * moment on screen -- which is all a property assertion can check.
 */
static void dump_reveal_and_pan(void)
{
    size_t duration_count = sizeof durations_c/sizeof durations_c[0];
    size_t amount_count = sizeof reveals_c/sizeof reveals_c[0];

    for (size_t d = 0; d < duration_count; ++d) {
        double duration = durations_c[d];
        for (int kind = 0; kind < 4; ++kind) {
            for (size_t i = 0; i < amount_count; ++i) {
                Timeline_View view = base_view(kind, duration);
                timeline_view_reveal(&view, duration, reveals_c[i]);
                printf("reveal %s %d %s %s %s %d\n", num(duration), kind,
                       num(reveals_c[i]), num(view.start_seconds),
                       num(view.span_seconds),
                       timeline_view_is_whole(&view, duration) ? 1 : 0);

                Timeline_View panned = base_view(kind, duration);
                timeline_view_pan(&panned, duration, reveals_c[i]);
                printf("pan %s %d %s %s %s %d\n", num(duration), kind,
                       num(reveals_c[i]), num(panned.start_seconds),
                       num(panned.span_seconds),
                       timeline_view_is_whole(&panned, duration) ? 1 : 0);
            }
        }
    }
}

/*
 * Follow-playback as it is actually used: reveal called once per frame while the
 * playhead advances across the whole track. This is the only shape in which the
 * margin's job -- not re-centring on every frame at the boundary
 * (`timeline_view.h:23-25`) -- is observable, because it depends on the *sequence*
 * of calls leaving the view alone until the playhead reaches the edge.
 */
static void dump_follow(void)
{
    size_t duration_count = sizeof durations_c/sizeof durations_c[0];
    for (size_t d = 0; d < duration_count; ++d) {
        double duration = durations_c[d];
        for (int kind = 1; kind < 3; ++kind) {
            Timeline_View view = base_view(kind, duration);
            for (int step = 0; step <= 97; ++step) {
                double playhead = duration*((double)step/97.0);
                timeline_view_reveal(&view, duration, playhead);
                printf("follow %s %d %d %s %s %s %d %s\n", num(duration), kind,
                       step, num(playhead), num(view.start_seconds),
                       num(view.span_seconds),
                       timeline_view_is_whole(&view, duration) ? 1 : 0,
                       num(timeline_view_x_at(&view, playhead, STRIP_LEFT,
                                              STRIP_WIDTH)));
            }
        }
    }
}

