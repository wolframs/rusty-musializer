static const double durations_d[] = {0.0, 0.1, 3.7, 240.0};

static void apply_op(Timeline_View *view, double duration, const struct Op *op)
{
    switch (op->kind) {
    case OP_RESET:  timeline_view_reset(view, duration); break;
    case OP_CLAMP:  timeline_view_clamp(view, duration); break;
    case OP_ZOOM:   timeline_view_zoom(view, duration, op->a, op->b); break;
    case OP_PAN:    timeline_view_pan(view, duration, op->a); break;
    default:        timeline_view_reveal(view, duration, op->a); break;
    }
}

